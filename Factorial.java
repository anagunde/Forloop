package practice;
// Factorial of a Number Find the factorial of a given number N using a for loop.

public class Factorial {
public static void main(String[] args) {
		
		int a;
		long Factorial = 1;
		
		for(a = 1; a <= 9; a++) {
			Factorial *=a;
			System.out.println("The Factorial Of Number Is " + Factorial);
		}
	}

}



